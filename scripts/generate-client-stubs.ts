/**
 * Generates TypeScript client stubs from `openapi/openapi.json` (BE-004).
 *
 *   npm run openapi:generate-clients
 *   → generated/clients/typescript/
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isDirectRun } from './openapi/is-direct-run.js';
import { listOpenApiOperations } from './openapi/list-operations.js';
import { loadOpenApiDocument, repoRoot } from './openapi/load-openapi.js';
import { renderClientMethod } from './openapi/render-client-method.js';
import { schemaToTsType, toSafeTypeName } from './openapi/schema-to-ts.js';
import type { OpenApiDocument } from './openapi/types.js';

function main(): void {
  const doc = loadOpenApiDocument();
  const outDir = join(repoRoot(), 'generated', 'clients', 'typescript');
  mkdirSync(outDir, { recursive: true });

  writeFileSync(join(outDir, 'types.ts'), renderTypes(doc), 'utf8');
  writeFileSync(join(outDir, 'client.ts'), renderClient(doc), 'utf8');
  writeFileSync(join(outDir, 'README.md'), renderReadme(doc), 'utf8');

  const ops = listOpenApiOperations(doc);
  console.log(
    `Generated TypeScript stubs: ${ops.length} operations, ${Object.keys(doc.components?.schemas ?? {}).length} schemas → ${outDir}`,
  );
}

function renderTypes(doc: OpenApiDocument): string {
  const lines: string[] = [
    '/**',
    ' * AUTO-GENERATED by scripts/generate-client-stubs.ts — do not edit.',
    ` * Source: openapi/openapi.json (${doc.info?.version ?? 'unknown'})`,
    ' */',
    '',
  ];

  for (const [name, schema] of Object.entries(doc.components?.schemas ?? {})) {
    if (!schema) continue;
    lines.push(
      `export type ${toSafeTypeName(name)} = ${schemaToTsType(doc, schema)};`,
      '',
    );
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

function renderClient(doc: OpenApiDocument): string {
  const ops = listOpenApiOperations(doc);
  const methods = ops
    .map((op) => renderClientMethod(doc, op.operation, op))
    .join('\n\n');

  return `/**
 * AUTO-GENERATED by scripts/generate-client-stubs.ts — do not edit.
 * Thin fetch stub for Mi IPTV OpenAPI MVP v${doc.info?.version ?? '1'}.
 */
import type * as Types from './types.js';

export type MiIptvClientOptions = {
  readonly baseUrl: string;
  readonly getAccessToken?: () => string | undefined | Promise<string | undefined>;
  /** Sprint-0 stand-in headers (e.g. x-account-id, x-profile-id, x-device-id). */
  readonly defaultHeaders?: Readonly<Record<string, string>>;
  readonly fetch?: typeof fetch;
};

export class MiIptvApiError extends Error {
  constructor(
    message: string,
    readonly status: number,
    readonly body: unknown,
  ) {
    super(message);
    this.name = 'MiIptvApiError';
  }
}

export class MiIptvApiClient {
  private readonly baseUrl: string;
  private readonly getAccessToken?: MiIptvClientOptions['getAccessToken'];
  private readonly defaultHeaders: Readonly<Record<string, string>>;
  private readonly fetchImpl: typeof fetch;

  constructor(options: MiIptvClientOptions) {
    this.baseUrl = options.baseUrl.replace(/\\/$/, '');
    this.getAccessToken = options.getAccessToken;
    this.defaultHeaders = options.defaultHeaders ?? {};
    this.fetchImpl = options.fetch ?? fetch;
  }

${methods}

  private buildPath(
    path: string,
    query: Readonly<Record<string, string | number | boolean | undefined>>,
  ): string {
    const params = new URLSearchParams();
    for (const [key, value] of Object.entries(query)) {
      if (value === undefined) continue;
      params.set(key, String(value));
    }
    const qs = params.toString();
    return qs.length === 0 ? path : \`\${path}?\${qs}\`;
  }

  private async request<T>(
    method: string,
    path: string,
    init?: { readonly body?: unknown; readonly auth?: boolean },
  ): Promise<T> {
    const headers: Record<string, string> = {
      accept: 'application/json',
      ...this.defaultHeaders,
    };
    if (init?.body !== undefined) {
      headers['content-type'] = 'application/json';
    }
    if (init?.auth !== false) {
      const token = await this.getAccessToken?.();
      if (token) {
        headers.authorization = \`Bearer \${token}\`;
      }
    }
    const response = await this.fetchImpl(\`\${this.baseUrl}\${path}\`, {
      method,
      headers,
      body: init?.body === undefined ? undefined : JSON.stringify(init.body),
    });
    const text = await response.text();
    const parsed: unknown = text.length === 0 ? undefined : JSON.parse(text);
    if (!response.ok) {
      throw new MiIptvApiError(
        \`\${method} \${path} failed with \${response.status}\`,
        response.status,
        parsed,
      );
    }
    return parsed as T;
  }
}
`;
}

function renderReadme(doc: OpenApiDocument): string {
  return `# Mi IPTV TypeScript client stubs

Generated from \`openapi/openapi.json\` (v${doc.info?.version ?? '1.0.0'}) by \`npm run openapi:generate-clients\`.

## Usage

\`\`\`ts
import { MiIptvApiClient } from './client.js';

const client = new MiIptvApiClient({
  baseUrl: 'http://localhost:4011', // OpenAPI mock (\`npm run mock:api\`)
  getAccessToken: () => process.env.MI_IPTV_ACCESS_TOKEN,
  defaultHeaders: {
    'x-account-id': process.env.MI_IPTV_ACCOUNT_ID ?? '',
  },
});

const health = await client.getHealth();
const hits = await client.searchCatalog({ q: 'news', limit: 10 });
\`\`\`

Query parameters are typed per operation. Custom headers such as \`x-account-id\` go through \`defaultHeaders\` (Sprint 0 stand-ins until JWT scope lands everywhere).

Regenerate after OpenAPI changes; do not hand-edit \`types.ts\` / \`client.ts\`.
`;
}

if (isDirectRun(import.meta.url)) {
  main();
}
